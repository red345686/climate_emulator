"""Common emulator interface and safe, explicit checkpoint operations."""
from __future__ import annotations

from abc import ABC, abstractmethod
from pathlib import Path
from typing import Any

import joblib
import numpy as np

from climate_emulator.data.preprocessing import PreparedData


class Emulator(ABC):
    """Physical-field prediction API; implementations never fit at import time."""

    @abstractmethod
    def fit(self, data: PreparedData, validation: PreparedData | None = None) -> "Emulator":
        """Fit only the explicitly supplied training data."""

    @abstractmethod
    def predict(self, data: PreparedData) -> np.ndarray:
        """Return physical predictions shaped (sample,lat,lon)."""

    def save(self, directory: str | Path) -> None:
        """Persist a classical emulator; load only trusted local checkpoints."""
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        joblib.dump(self, directory / "model.joblib")

    @staticmethod
    def load(directory: str | Path) -> Any:
        """Restore a trusted checkpoint generated by this project."""
        return joblib.load(Path(directory) / "model.joblib")


def restore_field(values: np.ndarray, mask: np.ndarray) -> np.ndarray:
    """Reconstruct physical grid cells without fabricating masked values."""
    result = np.full((len(values), *mask.shape), np.nan)
    result[:, mask] = values
    return result
